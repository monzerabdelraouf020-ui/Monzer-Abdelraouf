export function composeContextArabicFromGlosses(glosses: string[]): {
  literalAr: string;
  fluentArabic: string;
} {
  const cleaned = glosses.map((g) => g.trim()).filter(Boolean);
  const literalAr = cleaned.join(' ');
  const key = cleaned.join('|');

  const knownTemplates: Record<string, string> = {
    'أنا|أريد|ذهاب|مدرسة': 'أنا أريد الذهاب إلى المدرسة.',
    'أنا|أريد|ذهاب|جامعة': 'أنا أريد الذهاب إلى الجامعة.',
    'أنا|أريد|ذهاب|بيت': 'أنا أريد العودة إلى البيت.',
    'أهلاً|كيف حالك|اليوم': 'أهلاً بك، كيف حالك اليوم؟',
    'أهلاً|كيف حالك': 'أهلاً بك، كيف حالك؟',
    'أنا|بخير|شكراً': 'أنا بخير، شكراً جزيلاً لك.',
    'أنا|أحتاج|مساعدة|طوارئ|الآن': 'أحتاج إلى مساعدة طبية عاجلة الآن.',
    'أحتاج|مساعدة|الآن': 'أحتاج إلى المساعدة الآن.',
    'أنا|أحتاج|طبيب|الآن': 'أحتاج إلى مقابلة الطبيب الآن.',
    'شكراً|أنت|مساعدة|سعيد': 'شكراً جزيلاً لك على مساعدتك، أنا سعيد جداً.',
    'أنا|طالب|علم': 'أنا طالب وأهتم بدراسة العلوم.',
    'أنا|أحب|قراءة|كتاب': 'أنا أحب قراءة الكتب.',
    'من فضلك|انتظر': 'من فضلك انتظر قليلاً.',
    'نعم|فهم': 'نعم، لقد فهمت بوضوح.',
    'لا|فهم|سؤال': 'عذراً لم أفهم، هل يمكن إعادة السؤال؟',
  };

  if (knownTemplates[key]) {
    return { literalAr, fluentArabic: knownTemplates[key] };
  }

  // Syntactic Arabic sequence composition for arbitrary gloss combinations
  const mappedTokens: string[] = [];
  for (let i = 0; i < cleaned.length; i++) {
    const token = cleaned[i];
    const prev = cleaned[i - 1];
    if (token === 'ذهاب' && prev === 'أريد') {
      mappedTokens.push('الذهاب');
    } else if (token === 'مدرسة' && (prev === 'ذهاب' || prev === 'إلى')) {
      mappedTokens.push('إلى المدرسة');
    } else if (token === 'جامعة' && prev === 'ذهاب') {
      mappedTokens.push('إلى الجامعة');
    } else if (token === 'بيت' && prev === 'ذهاب') {
      mappedTokens.push('إلى البيت');
    } else if (token === 'مستشفى' && prev === 'ذهاب') {
      mappedTokens.push('إلى المستشفى');
    } else if (token === 'طوارئ' && prev === 'مساعدة') {
      mappedTokens.push('طبية عاجلة');
    } else if (token === 'مساعدة' && prev === 'أحتاج') {
      mappedTokens.push('إلى مساعدة');
    } else if (token === 'ماء' && prev === 'أريد') {
      mappedTokens.push('شرب الماء');
    } else {
      const dictEntry = ESL_DICTIONARY.find((d) => d.glossAr === token);
      mappedTokens.push(dictEntry ? dictEntry.arabicWord : token);
    }
  }

  const joined = mappedTokens.join(' ').trim();
  return {
    literalAr,
    fluentArabic: joined.endsWith('؟') || joined.endsWith('.') ? joined : `${joined}.`,
  };
}
